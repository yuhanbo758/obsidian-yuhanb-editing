// Based on the official obsidian-sample-plugin build configuration (0BSD).
import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { readFileSync } from 'node:fs';
const prod = process.argv[2] === 'production';
// Obsidian 只下载插件文件，构建产物必须自行携带再分发所需的许可和署名。
const notices = ['LICENSE', 'THIRD_PARTY_NOTICES.md', 'licenses/opencc-js-MIT.txt', 'licenses/Apache-2.0.txt', 'licenses/opencc-js-THIRD_PARTY_LICENSES.md']
  .map(file => readFileSync(new URL(file, import.meta.url), 'utf8').replace(/\r\n/g, '\n').trim())
  .join('\n\n').replaceAll('*/', '* /');
const context = await esbuild.context({
  banner: { js: `/* Generated by esbuild. Source: src/main.ts.\n${notices}\n*/` },
  entryPoints: ['src/main.ts'], bundle: true,
  external: ['obsidian', 'electron', '@codemirror/autocomplete', '@codemirror/collab', '@codemirror/commands', '@codemirror/language', '@codemirror/lint', '@codemirror/search', '@codemirror/state', '@codemirror/view', '@lezer/common', '@lezer/highlight', '@lezer/lr', ...builtinModules],
  format: 'cjs', target: 'es2021', logLevel: 'info', sourcemap: prod ? false : 'inline',
  treeShaking: true, outfile: 'main.js',
});
if (prod) { await context.rebuild(); await context.dispose(); } else { await context.watch(); }
